"""Консольная программа для сбора данных вычислительного эксперимента.

Запрашивает сведения об исследователе, эксперименте, количестве
и длительности запусков, а также о комплексном коэффициенте.
Вычисляет общее время, квадрат модуля коэффициента и выводит
информационную карточку с результатами и типами введённых данных.
"""

name=input("введите имя исследователя: ")
exp=input("введите название эксперимента: ")
count=int(input("введите количество запусков: "))
dur=float(input("введите длительность 1 запуска: "))
real,imag=map(float,input(
  "введите действительную и мнимую часть копмлексного числа: "
).split())

compx=complex(real,imag)
total=count*dur
totalm=total/60
sq=compx.real**2+compx.imag**2
has_runs=bool(count)

print()
print("="*40)
print(f"ЭКСПЕРИМЕНТ: {exp}")
print(f"Исследователь: {name}")
print(f"Запуски: {count}")
print(f"Общее время: {total:.2f} с ({totalm:.2f} мин)")
print(f"Коэффициент: {compx}")
print(f"Квадрат модуля: {sq:.2f}")
print(f"Есть выполненные запуски: {has_runs}")
print("="*40)

print(
  "Типы введённых значений:",
  type(name).__name__,
  type(exp).__name__,
  type(count).__name__,
  type(dur).__name__,
  type(real).__name__,
  type(imag).__name__,
)